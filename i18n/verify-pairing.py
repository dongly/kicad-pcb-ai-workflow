#!/usr/bin/env python3
"""Bilingual pairing verifier for the kicad-pcb-ai-workflow i18n (zh-CN) tree.

Adapted from deepseek-ai/deepseek-harness scripts/translation-pairing-record.ts
(line-based approximation of its mdast sectioning).

Conventions (see i18n/TRANSLATION-RULES.md):
- zh file:   i18n/zh-CN/<rel>.zh.md  mirrors repo-relative <rel>.md
- en file:   <rel>.md               (never modified by this tool)
- sidecar:   i18n/zh-CN/<rel>.i18n.yaml (generated by --write)
- sections:  YAML frontmatter is the preamble; every ATX heading starts a new
  section; fenced code blocks and i18n:generated regions are excluded from
  hashes. Code blocks and generated regions must be byte-identical on both
  sides. Section text is hashed as original line slices after CRLF-to-LF
  normalization; blank lines and trailing whitespace are preserved.
- hash:      sha256 of the section's original text lines joined with \n after
             CRLF-to-LF normalization, first 16 hex; whitespace is preserved.
- keys:      slug path built from ENGLISH headings (lowercase, non [a-z0-9] -> '_',
  trimmed, empty -> 'section'); '/' separates heading levels; duplicate keys get ~2, ~3 suffixes.

Usage:
  python i18n/verify-pairing.py                  # verify all pairs
  python i18n/verify-pairing.py --list           # status listing
  python i18n/verify-pairing.py --write --all    # rebuild every sidecar
  python i18n/verify-pairing.py --write <rel>.zh.md [more...]   # rebuild some
"""

import argparse
import hashlib
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
ZH_ROOT = REPO / "i18n" / "zh-CN"

KEY_LINE = re.compile(r"^(/[^\s:#]*):$")
HASH_LINE = re.compile(r"^ {2}(en|zh): ([0-9a-f]{16})$")
HEADING = re.compile(r"^#{1,6}(?:\s|$)")
FENCE = re.compile(r"^(`{3,}|~{3,})")
GEN_START = "<!-- i18n:generated:start -->"
GEN_END = "<!-- i18n:generated:end -->"

HEADER_TMPL = (
    "# Bilingual-pair consistency record for {en_rel}: per heading section, a hash of\n"
    "# its English and Chinese blocks outside code blocks and generated regions.\n"
    "# After editing either side, bring the other along and re-record with:\n"
    "#   python i18n/verify-pairing.py --write {zh_rel}\n"
)


def slug(text: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")
    return s or "section"


def parse_md(text: str):
    """Parse normalized markdown into (frontmatter_lines, sections, code_regions, gen_regions).

    sections: list of (heading_text_or_None, [non-blank, rstripped lines]).
    code_regions: full fenced regions including fence lines (normalized \\n joined).
    gen_regions: full generated regions including markers.
    """
    lines = text.replace("\r\n", "\n").split("\n")
    fm_lines = []
    body = lines
    if lines and lines[0].rstrip() == "---":
        for i in range(1, len(lines)):
            if lines[i].rstrip() == "---":
                fm_lines = lines[: i + 1]
                body = lines[i + 1 :]
                break
        if not fm_lines:  # unterminated frontmatter: treat whole file as body
            fm_lines, body = [], lines

    sections = [(None, fm_lines.copy())]
    code_regions = []
    gen_regions = []
    fence_char, fence_len, in_fence = "", 0, False
    in_gen = False
    gen_buf, code_buf = [], []

    for raw in body:
        line = raw.rstrip("\n")
        stripped = line.strip()
        if in_gen:
            gen_buf.append(line)
            if stripped == GEN_END:
                gen_regions.append("\n".join(gen_buf))
                gen_buf, in_gen = [], False
            continue
        if in_fence:
            code_buf.append(line)
            m = FENCE.match(stripped)
            if m and m.group(1)[0] == fence_char and len(m.group(1)) >= fence_len:
                code_regions.append("\n".join(code_buf))
                code_buf, in_fence = [], False
            continue
        if stripped == GEN_START:
            if gen_buf:
                gen_regions.append("\n".join(gen_buf))  # unterminated
                gen_buf = []
            gen_buf, in_gen = [line], True
            continue
        m = FENCE.match(stripped)
        if m:
            in_fence, fence_char, fence_len = True, m.group(1)[0], len(m.group(1))
            code_buf = [line]
            continue
        if HEADING.match(line):
            sections.append((line, []))
            continue
        sections[-1][1].append(line)

    if gen_buf:
        gen_regions.append("\n".join(gen_buf))
    if code_buf:
        code_regions.append("\n".join(code_buf))

    return sections, code_regions, gen_regions


def section_hash(lines) -> str:
    payload = "\n".join(lines)
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()[:16]


def key_path(stack) -> str:
    return "/" + "/".join(stack)


def build_records(en_path: Path, zh_path: Path):
    """Return (keys, en_hashes, zh_hashes, problems) or raise StructureError."""
    problems = []
    en_sections, en_code, en_gen = parse_md(en_path.read_text(encoding="utf-8"))
    zh_sections, zh_code, zh_gen = parse_md(zh_path.read_text(encoding="utf-8"))

    en_headings = [h for h, _ in en_sections if h is not None]
    zh_headings = [h for h, _ in zh_sections if h is not None]
    en_levels = [len(h) - len(h.lstrip("#")) for h in en_headings]
    zh_levels = [len(h) - len(h.lstrip("#")) for h in zh_headings]
    if len(en_headings) != len(zh_headings):
        problems.append(
            f"heading count mismatch: en={len(en_headings)} zh={len(zh_headings)} "
            f"(en headings: {en_headings[:6]}{'...' if len(en_headings) > 6 else ''})"
        )
    elif en_levels != zh_levels:
        problems.append(f"heading level/order mismatch: en={en_levels} zh={zh_levels}")

    if len(en_code) != len(zh_code):
        problems.append(f"code block count mismatch: en={len(en_code)} zh={len(zh_code)}")
    else:
        for i, (a, b) in enumerate(zip(en_code, zh_code)):
            if a != b:
                problems.append(f"code block #{i + 1} differs byte-wise between en/zh")

    if len(en_gen) != len(zh_gen):
        problems.append(f"generated region count mismatch: en={len(en_gen)} zh={len(zh_gen)}")
    else:
        for i, (a, b) in enumerate(zip(en_gen, zh_gen)):
            if a != b:
                problems.append(f"generated region #{i + 1} differs byte-wise between en/zh")

    n = min(len(en_sections), len(zh_sections))
    keys, en_hashes, zh_hashes = [], [], []
    stack = []
    seen = {}
    for i in range(n):
        h, en_lines = en_sections[i]
        _, zh_lines = zh_sections[i]
        if h is not None:
            level = len(h) - len(h.lstrip("#"))
            level = min(level, 6)
            del stack[level - 1 :]
            sl = slug(h.lstrip("#").strip())
            stack = stack[: level - 1] + [sl]
        base = key_path(stack) if h is not None else "/preamble"
        if base in seen:
            seen[base] += 1
            base = f"{base}~{seen[base]}"
        else:
            seen[base] = 1
        if not any(line.strip() for line in en_lines) and not any(line.strip() for line in zh_lines):
            continue
        keys.append(base)
        en_hashes.append(section_hash(en_lines))
        zh_hashes.append(section_hash(zh_lines))
    return keys, en_hashes, zh_hashes, problems


def parse_sidecar(path: Path):
    entries, order, cur = {}, [], None
    if not path.exists():
        return None, order
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.rstrip("\n")
        m = KEY_LINE.match(line)
        if m:
            cur = m.group(1)
            if cur in entries:
                raise ValueError(f"duplicate key in sidecar: {cur}")
            entries[cur] = {}
            order.append(cur)
            continue
        m = HASH_LINE.match(line)
        if m and cur is not None:
            entries[cur][m.group(1)] = m.group(2)
    return entries, order


def render_sidecar(en_rel: str, zh_rel: str, keys, en_hashes, zh_hashes) -> str:
    out = [HEADER_TMPL.format(en_rel=en_rel, zh_rel=zh_rel)]
    for k, e, z in zip(keys, en_hashes, zh_hashes):
        out.append(f"{k}:\n  en: {e}\n  zh: {z}\n")
    return "".join(out)


def iter_zh_files():
    if not ZH_ROOT.exists():
        return []
    return sorted(p for p in ZH_ROOT.rglob("*.zh.md") if p.is_file())


def zh_rel(p: Path) -> str:
    return p.relative_to(REPO).as_posix()


def en_of(zh_path: Path):
    rel = zh_path.relative_to(ZH_ROOT).with_suffix("")  # strips .md
    rel = Path(str(rel)[:-3] + ".md")  # strips .zh -> .md
    return REPO / rel, rel.as_posix()


def sidecar_of(zh_path: Path) -> Path:
    return zh_path.with_name(zh_path.name[: -len(".zh.md")] + ".i18n.yaml")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--write", nargs="*", metavar="ZH_REL", help="rebuild sidecars (no args = error; use --all)")
    ap.add_argument("--all", action="store_true", help="with --write: rebuild every pair")
    ap.add_argument("--list", action="store_true", help="status listing only")
    args = ap.parse_args(argv)

    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

    zh_files = iter_zh_files()
    if args.list:
        for p in zh_files:
            en_path, en_rel = en_of(p)
            sc = sidecar_of(p)
            if not en_path.exists():
                print(f"NO-EN      {zh_rel(p)}  (missing {en_rel})")
            elif not sc.exists():
                print(f"NO-RECORD  {zh_rel(p)}")
            else:
                keys, eh, zh_h, problems = build_records(en_path, p)
                try:
                    rec, _ = parse_sidecar(sc)
                except ValueError:
                    rec = None
                    problems.append("duplicate section key in sidecar")
                if rec is None:
                    problems.append("invalid or missing sidecar")
                else:
                    expected = {k: {"en": eh[i], "zh": zh_h[i]} for i, k in enumerate(keys)}
                    if rec != expected or render_sidecar(en_rel, zh_rel(p), keys, eh, zh_h) != sc.read_text(encoding="utf-8"):
                        problems.append("sidecar hashes or canonical format are stale")
                status = "STALE" if problems else "OK"
                print(f"{status:9}  {zh_rel(p)}")
        return 0

    if args.write is not None:
        targets = zh_files if args.all else [REPO / t for t in args.write]
        for p in targets:
            p = Path(p)
            en_path, en_rel = en_of(p)
            if not p.exists():
                print(f"SKIP (no zh file): {zh_rel(p)}", file=sys.stderr)
                continue
            if not en_path.exists():
                print(f"SKIP (no en file {en_rel}): {zh_rel(p)}", file=sys.stderr)
                continue
            keys, eh, zh_h, problems = build_records(en_path, p)
            if problems:
                print(f"REFUSE --write {zh_rel(p)}:", file=sys.stderr)
                for pr in problems:
                    print(f"  - {pr}", file=sys.stderr)
                return 1
            sc = sidecar_of(p)
            sc.parent.mkdir(parents=True, exist_ok=True)
            sc.write_text(render_sidecar(en_rel, zh_rel(p), keys, eh, zh_h), encoding="utf-8", newline="\n")
            print(f"WROTE  {zh_rel(sc)}  ({len(keys)} sections)")
        return 0

    # verify mode
    errors = 0
    if not zh_files:
        print("no .zh.md files under i18n/zh-CN yet")
        return 0
    for p in zh_files:
        en_path, en_rel = en_of(p)
        sc = sidecar_of(p)
        if not en_path.exists():
            print(f"ERROR {zh_rel(p)}: English counterpart missing: {en_rel}")
            errors += 1
            continue
        if not sc.exists():
            print(f"ERROR {zh_rel(p)}: sidecar missing: {zh_rel(sc)} (run --write)")
            errors += 1
            continue
        keys, eh, zh_h, problems = build_records(en_path, p)
        for pr in problems:
            print(f"ERROR {zh_rel(p)}: {pr}")
            errors += 1
        try:
            rec, order = parse_sidecar(sc)
        except ValueError as e:
            print(f"ERROR {zh_rel(sc)}: {e}")
            errors += 1
            continue
        if rec is None:
            continue
        rec_keys = list(rec.keys())
        missing = [k for k in keys if k not in rec]
        extra = [k for k in rec_keys if k not in set(keys)]
        for k in missing:
            print(f"ERROR {zh_rel(p)}: sidecar missing section {k}")
            errors += 1
        for k in extra:
            print(f"ERROR {zh_rel(p)}: sidecar has stale section {k}")
            errors += 1
        for i, k in enumerate(keys):
            if k not in rec:
                continue
            entry = rec[k]
            if entry.get("en") != eh[i]:
                print(f"ERROR {zh_rel(p)}: en hash mismatch at {k} (recorded {entry.get('en')}, actual {eh[i]})")
                errors += 1
            if entry.get("zh") != zh_h[i]:
                print(f"ERROR {zh_rel(p)}: zh hash mismatch at {k} (recorded {entry.get('zh')}, actual {zh_h[i]})")
                errors += 1
        canonical = render_sidecar(en_rel, zh_rel(p), keys, eh, zh_h)
        if not problems and not missing and not extra and canonical != sc.read_text(encoding="utf-8"):
            print(f"ERROR {zh_rel(sc)}: not canonical (run --write)")
            errors += 1
    if errors:
        print(f"\n{errors} error(s)")
        return 1
    print(f"OK: {len(zh_files)} pair(s) verified")
    return 0


if __name__ == "__main__":
    sys.exit(main())
